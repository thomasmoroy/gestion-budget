-- Migration initiale : schéma complet avec isolation par utilisateur
-- À exécuter dans l'éditeur SQL Supabase (ou automatiquement au démarrage du serveur).

CREATE TABLE IF NOT EXISTS accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'courant' CHECK (type IN ('courant', 'epargne', 'cash')),
  currency TEXT NOT NULL DEFAULT 'EUR',
  initial_balance BIGINT NOT NULL DEFAULT 0 CHECK (initial_balance >= -999999999999),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_accounts_user ON accounts (user_id);

CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('expense', 'income')),
  color TEXT NOT NULL DEFAULT '#8884d8',
  UNIQUE (user_id, name)
);
CREATE INDEX IF NOT EXISTS idx_categories_user ON categories (user_id);

CREATE TABLE IF NOT EXISTS recurring (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  label TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('expense', 'income')),
  amount BIGINT NOT NULL CHECK (amount > 0),
  date_day INTEGER NOT NULL DEFAULT 1 CHECK (date_day BETWEEN 1 AND 31),
  category_id BIGINT REFERENCES categories (id) ON DELETE SET NULL,
  account_id BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
  active BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS idx_recurring_user ON recurring (user_id);

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  account_id BIGINT NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
  category_id BIGINT REFERENCES categories (id) ON DELETE SET NULL,
  type TEXT NOT NULL CHECK (type IN ('expense', 'income')),
  amount BIGINT NOT NULL CHECK (amount > 0),
  date DATE NOT NULL,
  label TEXT NOT NULL,
  note TEXT,
  recurring_id BIGINT REFERENCES recurring (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_tx_user_date ON transactions (user_id, date);
CREATE INDEX IF NOT EXISTS idx_tx_user_account ON transactions (user_id, account_id);
CREATE INDEX IF NOT EXISTS idx_tx_user_category ON transactions (user_id, category_id);
CREATE INDEX IF NOT EXISTS idx_tx_recurring ON transactions (recurring_id, date);

CREATE TABLE IF NOT EXISTS budgets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
  month TEXT NOT NULL,
  amount BIGINT NOT NULL CHECK (amount >= 0),
  UNIQUE (category_id, month)
);
CREATE INDEX IF NOT EXISTS idx_budgets_user_month ON budgets (user_id, month);

CREATE TABLE IF NOT EXISTS recurring_generated (
  recurring_id BIGINT NOT NULL REFERENCES recurring (id) ON DELETE CASCADE,
  month TEXT NOT NULL,
  PRIMARY KEY (recurring_id, month)
);

-- Sécurité : RLS activé, aucun droit pour les rôles API (anon/authenticated)
-- → les données ne sont accessibles que via le serveur (rôle postgres, propriétaire,
-- qui fait lui-même le filtrage par user_id à partir du JWT Supabase vérifié).
ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE budgets ENABLE ROW LEVEL SECURITY;
ALTER TABLE recurring ENABLE ROW LEVEL SECURITY;
ALTER TABLE recurring_generated ENABLE ROW LEVEL SECURITY;

-- Révocation des droits API si les rôles Supabase existent (no-op ailleurs)
DO $$
DECLARE r TEXT;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA public FROM %I', r);
    END IF;
  END LOOP;
END $$;

